-- OMDB-CRAWLER-001: coverage of T_WC_OMDB_TITLE after the first daily runs.
-- Read-only (voie 1). Rerun as the table fills.

SELECT VAR_NAME, VAR_VALUE, TIM_UPDATED
FROM T_WC_SERVER_VARIABLE
WHERE VAR_NAME LIKE 'stromdbcrawler%'
ORDER BY VAR_NAME;

-- Rows per fetch day and answer
SELECT DATE(TIM_OMDB_FETCHED) AS DAY_, RESPONSE_OK, COUNT(*) AS ROWS_
FROM T_WC_OMDB_TITLE
GROUP BY DAY_, RESPONSE_OK
ORDER BY DAY_, RESPONSE_OK;

-- How much of each field is filled, on the answers found
SELECT OMDB_TYPE,
       COUNT(*) AS ROWS_,
       SUM(RT_SCORE IS NOT NULL) AS WITH_RT,
       SUM(METACRITIC_SCORE IS NOT NULL) AS WITH_METACRITIC,
       SUM(METASCORE IS NOT NULL) AS WITH_METASCORE,
       SUM(AWARDS IS NOT NULL) AS WITH_AWARDS,
       SUM(BOX_OFFICE_USD IS NOT NULL) AS WITH_BOX_OFFICE,
       SUM(IMDB_RATING IS NOT NULL) AS WITH_IMDB_RATING
FROM T_WC_OMDB_TITLE
WHERE RESPONSE_OK = 1
GROUP BY OMDB_TYPE
ORDER BY ROWS_ DESC;

-- Errors returned by OMDb
SELECT ERROR_TEXT, COUNT(*) AS ROWS_
FROM T_WC_OMDB_TITLE
WHERE RESPONSE_OK = 0
GROUP BY ERROR_TEXT
ORDER BY ROWS_ DESC
LIMIT 10;

-- Spot check on well-known titles (Inception, The Shawshank Redemption, Titanic, Breaking Bad)
SELECT ID_IMDB, TITLE, YEAR_TEXT, RT_SCORE, METACRITIC_SCORE, METASCORE,
       IMDB_RATING, IMDB_VOTES, BOX_OFFICE_USD, LEFT(AWARDS, 80) AS AWARDS_
FROM T_WC_OMDB_TITLE
WHERE ID_IMDB IN ('tt1375666', 'tt0111161', 'tt0120338', 'tt0903747');

-- The OMDb box office against the TMDb revenue, on movies fetched
SELECT COUNT(*) AS COMPARED,
       SUM(ABS(o.BOX_OFFICE_USD - m.REVENUE) <= 0.05 * m.REVENUE) AS WITHIN_5_PERCENT,
       SUM(o.BOX_OFFICE_USD < m.REVENUE) AS OMDB_LOWER
FROM T_WC_OMDB_TITLE o
JOIN T_WC_T2S_MOVIE m ON m.ID_IMDB = o.ID_IMDB
WHERE o.RESPONSE_OK = 1 AND o.BOX_OFFICE_USD > 0 AND m.REVENUE > 0;
